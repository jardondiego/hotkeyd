import Foundation

public enum ManPageGenerator {
    public static func defaultInstallURL() -> URL {
        if Paths.isEnvironmentOverrideActive {
            return Paths.root
                .appendingPathComponent("share/man/man1/hotkeyd.1")
        }
        return Paths.realHomeDirectory
            .appendingPathComponent(".local/share/man/man1/hotkeyd.1")
    }

    /// Generates a standards-compliant `man(7)` troff manual page (`hotkeyd(1)`) directly from
    /// `CommandRegistry` so documentation never drifts from CLI commands, flags, or exit codes.
    public static func generate(
        version: String,
        date: String = "2026-11-21",
        configPath: String = "~/.hotkeyd",
        logsPath: String = "~/Library/Application Support/Hotkeyd/logs",
        launchAgentPath: String = "~/Library/LaunchAgents/io.github.jardondiego.hotkeyd.daemon.plist"
    ) -> String {
        let manifest = CommandRegistry.manifest(
            version: version,
            configPath: configPath,
            logsPath: logsPath,
            launchAgentPath: launchAgentPath
        )

        var lines: [String] = []
        lines.append(".\\\" Generated by hotkeyd \(version) — regenerate via `hotkeyd man`")
        lines.append(".TH HOTKEYD 1 \"\(date)\" \"hotkeyd \(escapeRoffText(version))\" \"User Commands\"")

        // NAME
        lines.append(".SH NAME")
        lines.append("hotkeyd \\- global keyboard shortcuts and gestures for macOS")

        // SYNOPSIS
        lines.append(".SH SYNOPSIS")
        lines.append(".B hotkeyd")
        lines.append(".I command")
        lines.append("[\\fIarguments\\fR]")
        lines.append("[\\fIoptions\\fR]")
        lines.append(".br")
        lines.append(".B hotkeyd help")
        lines.append("[\\fIcommand\\fR]")

        // DESCRIPTION
        lines.append(".SH DESCRIPTION")
        lines.append(contentsOf: wrapProse(manifest.summary))
        lines.append(".PP")
        lines.append(contentsOf: wrapProse("All shortcuts live in a single mode-0600 JSON file at \(configPath). A LaunchAgent daemon watches the file and installs a CGEvent tap once macOS Accessibility permission is granted. Every command supports --json for structured scripting and AI agent integration."))

        // COMMANDS (grouped cleanly)
        lines.append(".SH COMMANDS")
        let groupedSections: [(title: String, filter: (CommandSpec) -> Bool)] = [
            ("Setup & Shell Integration", { ["init", "completions", "man"].contains($0.path.first ?? "") }),
            ("Shortcuts", { ["add", "set", "list", "show", "remove", "enable", "disable", "validate", "edit", "run", "migrate-actions"].contains($0.path.first ?? "") }),
            ("Daemon", { $0.path.first == "daemon" || ["pause", "resume", "panic"].contains($0.path.first ?? "") }),
            ("Caps Lock", { $0.path.first == "caps" }),
            ("Peek Overlay & Spotlight Search", { $0.path.first == "peek" }),
            ("Diagnostics & Introspection", { ["status", "logs", "stats", "doctor", "describe", "schema", "version"].contains($0.path.first ?? "") })
        ]

        var renderedPaths: Set<String> = []
        for section in groupedSections {
            let matching = manifest.commands.filter(section.filter)
            guard !matching.isEmpty else { continue }
            lines.append(".SS \(escapeRoffText(section.title))")
            for spec in matching {
                renderedPaths.insert(spec.displayName)
                appendCommandSpec(spec, to: &lines)
            }
        }

        // Catch-all for any future command added to CommandRegistry
        let remaining = manifest.commands.filter { !renderedPaths.contains($0.displayName) }
        if !remaining.isEmpty {
            lines.append(".SS Other Commands")
            for spec in remaining {
                appendCommandSpec(spec, to: &lines)
            }
        }

        // KEY SYNTAX
        lines.append(".SH KEY SYNTAX")
        lines.append(".TP")
        lines.append(".B Bare modifier double-taps")
        lines.append(contentsOf: wrapProse("Modifiers: \(manifest.conventions.modifiers.joined(separator: ", ")). Sided modifiers: \(manifest.conventions.sidedModifiers.joined(separator: ", ")). Example: lcmd, lopt, rcmd, fn, capsLock."))
        lines.append(".TP")
        lines.append(".B Key combinations")
        lines.append(contentsOf: wrapProse("Combine one or more modifiers with a key using '+'. Example: fn+space, capsLock+space, cmd+shift+c, fn+escape. Function keys f1..f20 may be bound bare."))
        lines.append(".TP")
        lines.append(".B Two-step sequences")
        lines.append(contentsOf: wrapProse("Tap and release a modifier leader, then press a bare key within maxSequenceDelayMs (default 250ms). Write '<modifier> > <key>' or shell-safe '<modifier>:<key>' (for example, 'fn > q' or fn:q). Unsided shift is forbidden as a sequence leader."))
        lines.append(".TP")
        lines.append(".B Reserved combinations")
        let reservedList = manifest.conventions.reservedCombos
            .map { "\($0.keys) (\($0.reason))" }
            .joined(separator: "; ")
        lines.append(contentsOf: wrapProse(reservedList))

        // CONFIGURATION
        lines.append(".SH CONFIGURATION")
        lines.append(contentsOf: wrapProse("Configuration is stored at \(configPath) as a regular file owned by the current user with permissions 0600 (O_NOFOLLOW enforced; symlinks are refused)."))
        lines.append(".PP")
        lines.append(contentsOf: wrapProse("Metacharacter-free commands matching native fast-path patterns bypass /bin/zsh and launch directly via NSWorkspace without Accessibility delegation: \(manifest.conventions.nativeFastPathPatterns.joined(separator: ", "))."))

        // ENVIRONMENT
        lines.append(".SH ENVIRONMENT")
        for key in manifest.conventions.env.keys.sorted() {
            guard let desc = manifest.conventions.env[key] else { continue }
            lines.append(".TP")
            lines.append(".B \(escapeRoffCode(key))")
            lines.append(contentsOf: wrapProse(desc))
        }

        // FILES
        lines.append(".SH FILES")
        lines.append(".TP")
        lines.append(".I \(escapeRoffCode(manifest.files.config))")
        lines.append(contentsOf: wrapProse("Primary JSON configuration file (mode 0600, regular file)."))
        lines.append(".TP")
        lines.append(".I \(escapeRoffCode(manifest.files.logs))")
        lines.append(contentsOf: wrapProse("Rotating daemon.log and actions.log files (mode 0600, 5 MiB rotation)."))
        lines.append(".TP")
        lines.append(".I \(escapeRoffCode(manifest.files.launchAgent))")
        lines.append(contentsOf: wrapProse("Per-user macOS LaunchAgent property list (mode 0600)."))

        // EXIT STATUS
        lines.append(".SH EXIT STATUS")
        let sortedCodes = manifest.conventions.exitCodes.keys.sorted { (Int($0) ?? 99) < (Int($1) ?? 99) }
        for code in sortedCodes {
            guard let desc = manifest.conventions.exitCodes[code] else { continue }
            lines.append(".TP")
            lines.append(".B \(escapeRoffCode(code))")
            lines.append(contentsOf: wrapProse(desc))
        }

        // EXAMPLES
        lines.append(".SH EXAMPLES")
        let examples: [(title: String, command: String)] = [
            ("Interactive first-time setup:", "hotkeyd init"),
            ("Bind double-tap Left Command to Chrome:", "hotkeyd add lcmd 'open -a \"Google Chrome\"'"),
            ("Bind a two-step sequence:", "hotkeyd add fn:q 'open -a Safari'"),
            ("Preview all shortcuts in the terminal or open Spotlight search:", "hotkeyd peek --terminal && hotkeyd peek --search"),
            ("Install zsh completions and manual page:", "hotkeyd completions zsh --install && hotkeyd man --install"),
            ("Verify system and daemon health:", "hotkeyd doctor")
        ]
        for (index, example) in examples.enumerated() {
            if index > 0 {
                lines.append(".PP")
            }
            lines.append(contentsOf: wrapProse(example.title))
            lines.append(".RS")
            lines.append(".nf")
            lines.append(escapeRoffCode(example.command))
            lines.append(".fi")
            lines.append(".RE")
        }

        // SEE ALSO
        lines.append(".SH SEE ALSO")
        lines.append(".BR launchctl (1),")
        lines.append(".BR hidutil (1),")
        lines.append(".BR codesign (1)")
        lines.append("")

        return lines.joined(separator: "\n")
    }

    private static func appendCommandSpec(_ spec: CommandSpec, to lines: inout [String]) {
        let argUsage = spec.args.map { $0.required ? "<\($0.name)>" : "[\($0.name)]" }.joined(separator: " ")
        let flagHint = spec.flags.isEmpty ? "" : " [options]"
        let header = "hotkeyd \(spec.displayName)" + (argUsage.isEmpty ? "" : " \(argUsage)") + flagHint

        lines.append(".TP")
        lines.append(".B \(escapeRoffCode(header))")
        lines.append(contentsOf: wrapProse(spec.description))
        if !spec.aliases.isEmpty {
            lines.append(".br")
            lines.append(contentsOf: wrapProse("Aliases: \(spec.aliases.joined(separator: ", "))."))
        }
        if !spec.flags.isEmpty {
            let flagNames = spec.flags.map { flag in
                flag.isBooleanSwitch ? flag.name : "\(flag.name) <\(flag.type)>"
            }.joined(separator: ", ")
            lines.append(".br")
            lines.append(contentsOf: wrapProse("Flags: \(flagNames)."))
        }
    }

    /// Word-wraps roff text to <= 76 bytes per line so `mandoc -Tlint` passes with zero warnings,
    /// protecting leading `.` or `'` characters on every wrapped line with `\&`.
    private static func wrapProse(_ raw: String, maxBytes: Int = 76) -> [String] {
        let cleaned = raw
            .replacingOccurrences(of: "`", with: "")
            .replacingOccurrences(of: "\r\n", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
        let words = cleaned.split(whereSeparator: { $0 == " " || $0 == "\t" }).map(String.init)
        guard !words.isEmpty else { return [] }

        var result: [String] = []
        var current = ""

        for rawWord in words {
            let token = escapeRoffToken(rawWord)
            if current.isEmpty {
                current = protectLeadingRoffControl(token)
            } else if current.utf8.count + 1 + token.utf8.count <= maxBytes {
                current += " " + token
            } else {
                result.append(current)
                current = protectLeadingRoffControl(token)
            }
        }
        if !current.isEmpty {
            result.append(current)
        }
        return result
    }

    private static func escapeRoffToken(_ raw: String) -> String {
        raw
            .replacingOccurrences(of: "\\", with: "\\e")
            .replacingOccurrences(of: "-", with: "\\-")
    }

    private static func protectLeadingRoffControl(_ text: String) -> String {
        if text.hasPrefix(".") || text.hasPrefix("'") {
            return "\\&" + text
        }
        return text
    }

    private static func escapeRoffText(_ raw: String) -> String {
        let collapsed = raw
            .replacingOccurrences(of: "\r\n", with: " ")
            .replacingOccurrences(of: "\n", with: " ")
        return protectLeadingRoffControl(escapeRoffToken(collapsed))
    }

    private static func escapeRoffCode(_ raw: String) -> String {
        escapeRoffText(raw)
    }
}
